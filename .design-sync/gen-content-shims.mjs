// design-sync buildCmd (part 1 of 2; see also the symlink in cfg.buildCmd).
// Regenerates every derived sync input so the bundle never drifts from source:
//   1. esbuild-resolvable shims for Vite's `?raw` md imports in src/i18n.jsx
//      (mapped via .design-sync/tsconfig.json paths)
//   2. a 1x1 PNG placeholder for the absolute `/assets/bg-hero.jpg` url in
//      Hero.css (esbuild can't resolve absolute site paths; also mapped via
//      tsconfig paths — the real photo comes back via the CSS in step 3)
//   3. .cache/styles-entry.css (cfg.cssEntry): src/styles/global.css inlined
//      (it's only imported by main.jsx, so the bundle never sees it) + data-URI
//      overrides that restore the three /assets/* images that only exist on
//      the deployed site (hero bg, hosts photo, header logo), downscaled via
//      macOS `sips`.
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = join(here, '..')
const cache = join(here, '.cache')
const shimDir = join(cache, 'content-shims')
const assetDir = join(cache, 'assets')
mkdirSync(shimDir, { recursive: true })
mkdirSync(assetDir, { recursive: true })

// 1. content shims
for (const lang of ['be', 'en']) {
  const raw = readFileSync(join(repo, 'content', `${lang}.md`), 'utf8')
  writeFileSync(join(shimDir, `${lang}.js`), `export default ${JSON.stringify(raw)};\n`)
}
console.log('content shims: be.md, en.md')

// 2. 1x1 transparent png placeholder (unblocks esbuild css url() resolution)
writeFileSync(
  join(assetDir, 'blank.png'),
  Buffer.from(
    'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==',
    'base64',
  ),
)

// 3. downscaled data-URI overrides
function downscale(name, maxPx) {
  const src = join(repo, 'public', 'assets', name)
  const dst = join(assetDir, name)
  execFileSync('sips', ['-Z', String(maxPx), '-s', 'format', 'jpeg', '-s', 'formatOptions', '72', src, '--out', dst], {
    stdio: 'pipe',
  })
  return `data:image/jpeg;base64,${readFileSync(dst).toString('base64')}`
}
const heroBg = downscale('bg-hero.jpg', 1600)
const hosts = downscale('hosts.jpg', 900)
const favicon = downscale('favicon.jpg', 128)

// The override must repeat Hero.css's gradient exactly — assert it still matches.
const heroGradient =
  'linear-gradient(180deg,rgba(20,16,11,.55) 0%,rgba(20,16,11,.15) 40%,rgba(20,16,11,.82) 88%,var(--night) 100%)'
const heroCss = readFileSync(join(repo, 'src', 'components', 'Hero.css'), 'utf8')
if (!heroCss.includes(heroGradient) || !heroCss.includes('url("/assets/bg-hero.jpg")')) {
  throw new Error(
    'Hero.css background changed — update the gradient/override in .design-sync/gen-content-shims.mjs to match',
  )
}

const globalCss = readFileSync(join(repo, 'src', 'styles', 'global.css'), 'utf8')
writeFileSync(
  join(cache, 'styles-entry.css'),
  `/* generated by .design-sync/gen-content-shims.mjs — do not edit */
/* ── src/styles/global.css (inlined: only main.jsx imports it, the bundle doesn't) ── */
${globalCss}
/* ── site-asset restoration: /assets/* only exists on the deployed site ── */
.hero{background-image:${heroGradient},url("${heroBg}") !important}
img[src="/assets/hosts.jpg"]{content:url("${hosts}")}
img[src="/assets/favicon.jpg"]{content:url("${favicon}")}
`,
)
console.log('styles-entry.css generated (global.css + 3 embedded assets)')
